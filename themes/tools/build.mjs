import { mkdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { parseArgs } from 'node:util';
import { GIT_REV, THEME_LIMITS } from '../../desktop/src/lib/themes/rules.ts';
import { commitTime, previousIndex, repoRoot, tryGit } from './git.mjs';
import { print, table, writeSummary } from './summary.mjs';
import { listThemes, loadTheme, readRevoked } from './theme.mjs';

const README = 'Generated by .github/workflows/themes.yml from main, do not edit.\n';

const { values } = parseArgs({
  options: {
    rev: { type: 'string' },
    out: { type: 'string' },
    previous: { type: 'string' },
  },
});

function fatal(message) {
  console.error(`fatal: ${message}`);
  process.exit(1);
}

if (!values.out || !values.rev || !GIT_REV.test(values.rev)) {
  fatal('usage: build.mjs --rev <40 hex sha> --out <dir> [--previous <git-ref>]');
}

const root = repoRoot();
const rev = values.rev;
if (tryGit(root, ['cat-file', '-t', rev]) !== 'commit') fatal(`${rev} is not a commit`);
const revoked = readRevoked(root);
if (!revoked) fatal('themes/revoked.json must be a list of {id, hash, reason}');

let previous;
try {
  previous = previousIndex(root, values.previous);
} catch (error) {
  fatal(`previous index: ${error.message}`);
}
const before = new Map((previous?.themes ?? []).map((theme) => [theme.id, theme]));
const present = listThemes(root);
const ids = [...new Set([...present, ...before.keys()])].sort();
const isRevoked = (id, hash) => revoked.some((item) => item.id === id && item.hash === hash);

const themes = [];
const rows = [];
let failed = false;

for (const id of ids) {
  const old = before.get(id);
  if (!present.includes(id)) {
    rows.push([id, 'left out', old?.version ?? '-', ['folder removed']]);
    continue;
  }
  const { entry, errors } = loadTheme(join(root, 'themes', id), rev, old);
  for (const line of errors) print(`error: ${line}`);
  if (entry && isRevoked(id, entry.hash)) {
    rows.push([id, 'revoked', entry.version, []]);
  } else if (entry) {
    themes.push(entry);
    rows.push([id, 'published', entry.version, []]);
  } else {
    failed = true;
    if (old && !isRevoked(id, old.hash)) {
      themes.push(old);
      rows.push([id, 'kept previous', old.version, errors]);
    } else {
      rows.push([id, 'left out', '-', errors]);
    }
  }
}

const index = {
  schema: 1,
  generated: commitTime(root, rev),
  rev,
  themes: themes.sort((a, b) => (a.id < b.id ? -1 : 1)),
  revoked: revoked.map(({ id, hash }) => ({ id, hash })),
};
const json = JSON.stringify(index);
if (Buffer.byteLength(json) > THEME_LIMITS.indexBytes) fatal('index.json is bigger than 2 MiB');

const out = resolve(values.out);
mkdirSync(join(out, 'v1'), { recursive: true });
writeFileSync(join(out, 'v1', 'index.json'), json);
writeFileSync(join(out, 'README.md'), README);

writeSummary(`### Themes publish\n\n${table(['Theme', 'Status', 'Version', 'Errors'], rows)}`);
for (const [id, status, version] of rows) print(`${id} ${version}: ${status}`);
console.log(`${themes.length} published, ${revoked.length} revoked`);
process.exit(failed ? 3 : 0);
