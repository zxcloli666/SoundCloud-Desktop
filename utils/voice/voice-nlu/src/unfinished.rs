pub fn sounds_unfinished(text: &str) -> bool {
    let Some(last) = text.split_whitespace().last() else {
        return false;
    };
    let last = last
        .trim_matches(|c: char| !c.is_alphanumeric())
        .to_lowercase()
        .replace('ё', "е");
    DANGLING.contains(&last.as_str())
}
