#[test]
fn a_no_inside_a_retold_exchange_is_the_other_person_answering() {
    stays_silent(&[
        "я ему говорю сделай громче а он мне нет тише",
        "я сказала стоп а он нет продолжай",
        "он говорит громче нет говорю тише",
        "я ему громче а он нет тише",
        "я попросила потише а она нет громче",
        "мы им громче а они нет тише",
    ]);
    acts(&[
        ("громче нет тише", "volume_down"),
        ("я говорю громче нет тише", "volume_down"),
        ("следующий ой назад", "previous"),
        ("включи басту нет скриптонита", "play"),
        ("сделай громче она говорит тихо", "volume_up"),
    ]);
    let p = &parse("включи ему басту нет скриптонита", &Names::default())[0];
    assert!(p.queries.iter().any(|q| q.text == "скриптонита"));
    assert!(!p.queries.iter().any(|q| q.text.contains("баст")));
}

