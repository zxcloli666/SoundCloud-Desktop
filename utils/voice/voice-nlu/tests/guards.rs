use voice_nlu::{Names, parse};

fn steps(text: &str) -> Vec<&'static str> {
    parse(text, &Names::default())
        .iter()
        .map(|p| p.intent.name())
        .collect()
}

fn stays_silent(phrases: &[&str]) {
    for text in phrases {
        assert_eq!(steps(text), ["none"], "{text}");
    }
}

fn acts(rows: &[(&str, &str)]) {
    for (text, want) in rows {
        assert_eq!(steps(text), [*want], "{text}");
    }
}

#[test]
fn a_direction_word_taken_by_the_subject_or_verb_after_it_is_talk() {
    stays_silent(&[
        "дальше я сам разберусь спасибо",
        "дальше сам разберёшься",
        "дальше я не помню как там поётся",
        "ну дальше ты сама",
        "а дальше я пойду спать",
        "назад назад отходим нас тут всех положат",
        "назад я уже не вернусь",
        "вперёд мы не пойдём",
        "обратно поедем на такси",
        "давай дальше я сам",
    ]);
    acts(&[
        ("дальше эта какая-то грустная", "next"),
        ("дальше мне эта не нравится", "next"),
        ("дальше давай", "next"),
        ("включи дальше я устала", "next"),
        ("назад верни", "previous"),
        ("назад на 10 секунд", "seek_backward"),
        ("перемотай назад я прослушал", "seek_backward"),
        ("вперёд секунд на двадцать", "seek_forward"),
    ]);
}

#[test]
fn next_or_previous_said_of_a_thing_that_is_not_music_is_talk() {
    stays_silent(&[
        "следующий пациент заходите",
        "следующий кандидат опоздал",
        "следующий клиент ждёт",
        "следующая остановка конечная выходим",
        "следующую остановку проехали",
        "следующее задание делаем вместе",
        "прошлую зиму помнишь",
        "прошлый год был лучше",
        "ну давайте следующий тост за родителей",
    ]);
    acts(&[
        ("следующий трек", "next"),
        ("следующая песня пожалуйста", "next"),
        ("следующий давай", "next"),
        ("следующую хочу", "next"),
        ("следующую эта надоела", "next"),
        ("следующий этот уже надоел", "next"),
        ("следующий мне не нравится этот", "next"),
        ("предыдущая была лучше", "previous"),
        ("прошлый трек", "previous"),
    ]);
}

#[test]
fn a_phrase_blocked_as_a_whole_is_not_cut_into_commands() {
    stays_silent(&[
        "следующий раз я сама выберу что слушать",
        "в следующий раз включи что-нибудь повеселее",
        "следующий раз ставь потише",
        "дальше сам разберёшься пауза",
        "следующий пациент следующий",
    ]);
    acts(&[("следующий", "next"), ("следующий трек", "next")]);
    assert_eq!(steps("следующий и погромче"), ["next", "volume_up"]);
}

#[test]
fn a_command_word_that_is_half_of_a_compound_is_talk() {
    stays_silent(&[
        "стоп кран сорвали",
        "стоп сигнал горит",
        "стоп слово забыли",
        "стоп кадр получился",
        "стоп линию проехали",
        "кто то стоп кран сорвал",
        "плей офф",
        "плей офф начинается завтра",
    ]);
    acts(&[
        ("стоп", "stop"),
        ("стоп мама звонит", "stop"),
        ("стоп сосед пришёл", "stop"),
        ("стоп хватит уже", "stop"),
        ("пауза курьер пришёл", "pause"),
        ("включи стоп кран", "play"),
    ]);
}

