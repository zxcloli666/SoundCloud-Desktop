#[test]
fn the_taste_of_another_person_is_not_a_like_or_a_skip() {
    stays_silent(&[
        "тебе нравится эта песня или переключить",
        "тебе нравится эта песня",
        "вам нравится этот трек",
        "какая песня тебе нравится",
        "а тебе нравится",
        "тебе не нравится эта песня",
        "тебе не надоело это",
        "ему понравилась эта песня",
    ]);
    acts(&[
        ("мне нравится эта песня", "like"),
        ("нравится", "like"),
        ("это мне нравится", "like"),
        ("мне не нравится эта песня", "next"),
        ("предыдущая была лучше", "previous"),
    ]);
}

#[test]
fn a_volume_command_about_another_thing_is_said_to_its_owner() {
    stays_silent(&[
        "сделай потише свой телефон люди же спят",
        "сделай потише свой телефон",
        "выключи свою шарманку наконец",
        "убавь свои наушники",
        "включи громче свой будильник там не слышно",
        "сделай потише телефон люди же спят",
        "сделай громче будильник",
        "убавь компьютер",
    ]);
    acts(&[
        ("сделай потише", "volume_down"),
        ("сделай потише музыку", "volume_down"),
        ("сделай потише я разговариваю по телефону", "volume_down"),
        ("сделай потише телефон звонит", "volume_down"),
        ("пауза телефон звонит", "pause"),
        ("хочу свои лайки", "play_likes"),
        ("включи свою любимую", "play_likes"),
        ("включи свой среди чужих", "play"),
    ]);
}

#[test]
fn a_which_question_with_a_verb_that_is_not_about_playing_asks_something_else() {
    stays_silent(&[
        "какой трек у тебя на звонке стоит",
        "какой трек у тебя на будильнике стоит",
        "какой трек он выбрал",
        "какая песня тебе больше заходит",
        "какой трек у вас в машине крутится",
        "какой трек мы вчера слушали",
    ]);
    acts(&[
        ("какой трек играет", "now_playing"),
        ("какая песня сейчас играет", "now_playing"),
        ("какой трек у тебя сейчас играет", "now_playing"),
        ("какая это песня", "now_playing"),
        ("как называется этот трек", "now_playing"),
    ]);
}
