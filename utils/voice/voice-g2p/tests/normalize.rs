use voice_g2p::ru::Normalizer;

fn check(cases: &[(&str, &str)]) {
    let n = Normalizer::new();
    let mut bad = Vec::new();
    for (input, want) in cases {
        let got = n.run(input);
        if got != *want {
            bad.push(format!("{input:?}\n  want {want:?}\n  got  {got:?}"));
        }
    }
    assert!(bad.is_empty(), "\n{}", bad.join("\n"));
}

#[test]
fn numbers_in_assistant_phrases() {
    check(&[
        ("громкость 50", "громкость пятьдесят"),
        ("Громкость 1", "громкость один"),
        ("через 30 секунд", "через тридцать секунд"),
        ("через 1 минуту", "через одну минуту"),
        ("через 2 минуты", "через две минуты"),
        ("1 трек", "один трек"),
        ("2 трека", "два трека"),
        ("5 треков", "пять треков"),
        ("21 трек", "двадцать один трек"),
        ("22 песни", "двадцать две песни"),
        ("трек номер 3", "трек номер три"),
        ("3-й трек", "третий трек"),
        ("в 3-м треке", "в третьем треке"),
        ("до 5 минут", "до пяти минут"),
        ("к 10 часам", "к десяти часам"),
        ("0", "ноль"),
        ("громкость 100", "громкость сто"),
        ("1999 слушателей", "тысяча девятьсот девяносто девять слушателей"),
        ("2000 треков", "две тысячи треков"),
        ("123456", "сто двадцать три тысячи четыреста пятьдесят шесть"),
        ("в 2024 году", "в две тысячи двадцать четвёртом году"),
        ("в 1990 году", "в тысяча девятьсот девяностом году"),
        ("в 90-х", "в девяностых"),
        ("1 000 000", "один миллион"),
    ]);
}

#[test]
fn times_dates_units() {
    check(&[
        ("в 17:45", "в семнадцать сорок пять"),
        ("в 9:05", "в девять ноль пять"),
        ("в 10:00", "в десять часов"),
        ("12.03.2024", "двенадцатое марта две тысячи двадцать четвёртого года"),
        ("50%", "пятьдесят проц+ентов"),
        ("1%", "один проц+ент"),
        ("2 %", "два проц+ента"),
        ("громкость 25%", "громкость двадцать пять проц+ентов"),
        ("3,5 км", "три целых пять десятых километра"),
        ("-5°C", "минус пять гр+адусов цельсия"),
        ("120 BPM", "сто двадцать уд+аров в мин+уту"),
        ("100 ₽", "сто рубл+ей"),
        ("21 °C", "двадцать один гр+адус цельсия"),
    ]);
}

#[test]
fn abbreviations_and_latin() {
    check(&[
        ("т.е. так", "то есть так"),
        ("ставь и т.д.", "ставь и так далее"),
        ("включи The Weeknd", "включи зе уик+энд"),
        ("Imagine Dragons, Coldplay", "им+аджин др+агонс, к+олдплей"),
        ("DJ Snake", "ди дж+ей снэйк"),
        ("USB", "ю эс б+и"),
    ]);
}
