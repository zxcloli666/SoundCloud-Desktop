#[test]
fn ipa_for_words() {
    let ru = Russian::bundled();
    let mut bad = Vec::new();
    for (input, want) in CASES {
        let got = ru.speak(input).ipa;
        if got != *want {
            bad.push(format!("{input}: want {want} got {got}"));
        }
    }
    assert!(CASES.len() >= 100);
    assert!(bad.is_empty(), "\n{}", bad.join("\n"));
}
